#!/usr/bin/env bash
# Writes each brain case's prompt.md, whose frontmatter supplies
# execution.model and execution.append_system_prompt from agents/brain.md.
# Every case runs the model brain.md has on disk, whatever the source of its
# prompt, so the arms differ only in the prompt. claude plugin eval merges
# prompt.md over case.yaml, and case.yaml sets append_system_prompt to null
# so a case without prompt.md fails to load. prompt.md is generated and ignored by
# version control: run this before claude plugin eval.
# Each entry in `cases` is "<case>:<source>", where <source> is one of:
#   (empty)       the brain.md body as it is on disk;
#   <section>     that body without the "# <section>" heading and its text;
#   rev:<rev>     the brain.md body at jujutsu revision <rev>, so a baseline
#                 arm can be the prompt as it was before a change.
# With --check, exits 1 if any prompt.md is missing or out of date and
# changes nothing.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
brain="$here/../../agents/brain.md"

cases=(
  "buried-ask:"
  "buried-ask-baseline:How you report"
  "buried-ask-prior:rev:yomnrxus"
  "label-only:"
  "label-only-baseline:rev:qwwwnysq"
  "answer-fidelity:"
  "answer-fidelity-option:"
  "answer-fidelity-baseline:rev:olmkuzsk"
  "answer-fidelity-option-baseline:rev:olmkuzsk"
)

# Strips the frontmatter and leading blank lines from brain.md on stdin.
body() { awk 'BEGIN{n=0} /^---$/ && n<2 {n++; next} n>=2' | sed '/./,$!d'; }
without_section() {
  SECTION="$1" awk '$0 == "# " ENVIRON["SECTION"] {skip=1; next} /^# / {skip=0} !skip' |
    sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'
}

# Prints prompt.md: frontmatter only, with the text as a block scalar. The
# comment after the block keeps the text's final newline, which the closing
# "---" would otherwise take.
render() {
  local source="$1" model="$2" text="$3"
  printf -- '---\n'
  printf 'model: %s\n' "$model"
  printf 'append_system_prompt: |\n'
  printf '%s\n' "$text" | awk '{ print ($0 == "" ? "" : "  " $0) }'
  printf '# Generated by sync-system-prompt.sh from agents/brain.md (%s); do not edit.\n' \
    "${source:-as on disk}"
  printf -- '---\n'
}

full="$(body < "$brain")"
model="$(awk '/^---$/ { n++; next } n == 1 && /^model: / { print $2 }' "$brain")"
if [[ -z "$model" ]]; then
  echo "brain.md has no model in its frontmatter" >&2
  exit 1
fi
status=0
for entry in "${cases[@]}"; do
  name="${entry%%:*}"; source="${entry#*:}"
  case "$source" in
    "") text="$full" ;;
    rev:*)
      rev="${source#rev:}"
      text="$(cd "$here" && jj --ignore-working-copy file show -r "$rev" "$brain" | body)"
      if [[ -z "$text" ]]; then
        echo "$name: no brain.md body at revision $rev" >&2
        exit 1
      fi
      ;;
    *)
      if ! grep -qxF "# $source" <<<"$full"; then
        echo "$name: brain.md has no \"# $source\" section" >&2
        exit 1
      fi
      text="$(printf '%s\n' "$full" | without_section "$source")"
      ;;
  esac
  out="$here/$name/prompt.md"
  want="$(render "$source" "$model" "$text")"
  if [[ "${1:-}" == "--check" ]]; then
    if [[ ! -f "$out" ]] || ! diff -q "$out" <(printf '%s\n' "$want") >/dev/null; then
      echo "$name/prompt.md is missing or out of date; run $0" >&2
      status=1
    fi
  else
    printf '%s\n' "$want" > "$out"
  fi
done
exit "$status"
