#!/usr/bin/env bash
# Writes each junior case's prompt.md, whose frontmatter supplies
# execution.model and execution.append_system_prompt from agents/junior.md,
# so each case runs the model and body the agent ships with. claude plugin
# eval merges prompt.md over case.yaml, and case.yaml sets
# append_system_prompt to null so a case without prompt.md fails to load.
# prompt.md is generated and ignored by version control: run this before
# claude plugin eval.
# Each entry in `cases` is "<case>:<source>", where <source> is one of:
#   (empty)       the junior.md body as it is on disk;
#   rule:<text>   that body without the top-level bullet whose first line
#                 starts with "- <text>";
#   report        that body without the "Report in this shape" paragraph
#                 and the list under it.
# With --check, exits 1 if any prompt.md is missing or out of date and
# changes nothing.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
junior="$here/../../agents/junior.md"

cases=(
  "scope:"
  "stale-line:"
  "stale-line-baseline:rule:A line number in the brief"
  "gap:"
  "verify:"
  "report-shape:"
  "report-shape-baseline:report"
)

# Strips the frontmatter and leading blank lines from junior.md on stdin.
body() { awk 'BEGIN{n=0} /^---$/ && n<2 {n++; next} n>=2' | sed '/./,$!d'; }
trim_trailing_blank() { sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'; }
without_rule() {
  PREFIX="- $1" awk '
    index($0, ENVIRON["PREFIX"]) == 1 { skip = 1; next }
    skip && /^  / { next }
    { skip = 0; print }
  '
}
without_report() { awk '/^Report in this shape/ { exit } { print }' | trim_trailing_blank; }

# Prints prompt.md: frontmatter only, with the text as a block scalar. The
# comment after the block keeps the text's final newline, which the closing
# "---" would otherwise take.
render() {
  local source="$1" model="$2" text="$3"
  printf -- '---\n'
  printf 'model: %s\n' "$model"
  printf 'append_system_prompt: |\n'
  printf '%s\n' "$text" | awk '{ print ($0 == "" ? "" : "  " $0) }'
  printf '# Generated by sync-system-prompt.sh from agents/junior.md (%s); do not edit.\n' \
    "${source:-as on disk}"
  printf -- '---\n'
}

full="$(body < "$junior")"
model="$(awk '/^---$/ { n++; next } n == 1 && /^model: / { print $2 }' "$junior")"
status=0
for entry in "${cases[@]}"; do
  name="${entry%%:*}"; source="${entry#*:}"
  case "$source" in
    "") text="$full" ;;
    report)
      text="$(printf '%s\n' "$full" | without_report)"
      ;;
    rule:*)
      text="$(printf '%s\n' "$full" | without_rule "${source#rule:}")"
      ;;
  esac
  if [[ "$text" == "$full" ]]; then
    [[ -z "$source" ]] || { echo "$name: junior.md has no part matching \"$source\"" >&2; exit 1; }
  fi
  out="$here/$name/prompt.md"
  want="$(render "$source" "$model" "$text")"
  if [[ "${1:-}" == "--check" ]]; then
    if [[ ! -f "$out" ]] || ! diff -q "$out" <(printf '%s\n' "$want") >/dev/null; then
      echo "$name/prompt.md is missing or out of date; run $0" >&2
      status=1
    fi
  else
    printf '%s\n' "$want" > "$out"
  fi
done
exit "$status"
