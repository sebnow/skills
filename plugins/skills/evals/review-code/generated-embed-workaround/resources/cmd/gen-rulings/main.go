// Command gen-rulings writes internal/tax/pl/rulings_text.go from
// docs/rulings/pl/*/text.md.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
)

func main() {
	paths, err := filepath.Glob("../../../docs/rulings/pl/*/text.md")
	if err != nil {
		fail(err)
	}
	sort.Strings(paths)

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gen-rulings. DO NOT EDIT.\n\n")
	b.WriteString("package pl\n\n")
	b.WriteString("var rulingText = map[string]string{\n")
	for _, p := range paths {
		text, err := os.ReadFile(p)
		if err != nil {
			fail(err)
		}
		sig := filepath.Base(filepath.Dir(p))
		fmt.Fprintf(&b, "\t%q: %q,\n", sig, text)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("rulings_text.go", src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
